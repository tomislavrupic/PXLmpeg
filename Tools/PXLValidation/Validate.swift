import Foundation
import PXLAppleMedia
import PXLMedia
import PXLTestSupport
import PXLmpeg

private struct CaseReport: Codable {
  let name: String, frames: Int
  let warmup: JobReceipt
  let runs: [JobReceipt]
  var medianSeconds: Double {
    let values = runs.map(\.elapsedSeconds).sorted()
    return values[values.count / 2]
  }
}
private struct Report: Codable {
  let os: String, processorCount: Int, physicalMemory: UInt64, thermalState: String
  let generatedAt: Date
  let cases: [CaseReport]
}
@main struct Validate {
  static func main() async throws {
    if CommandLine.arguments.dropFirst().first == "remux" {
      try await RemuxValidation.run(Array(CommandLine.arguments.dropFirst(2)))
      return
    }
    if CommandLine.arguments.dropFirst().first == "hdr" {
      try await HDRValidation.run(Array(CommandLine.arguments.dropFirst(2)))
      return
    }
    if CommandLine.arguments.dropFirst().first == "wide" {
      try await WideFootageValidation.run(Array(CommandLine.arguments.dropFirst(2)))
      return
    }
    if CommandLine.arguments.dropFirst().first == "bframes" {
      try await BFrameValidation.run(Array(CommandLine.arguments.dropFirst(2)))
      return
    }
    guard CommandLine.arguments.count == 2 else {
      throw NSError(domain: "Usage: pxl-validation OUTPUT_DIRECTORY", code: 2)
    }
    let directory = URL(fileURLWithPath: CommandLine.arguments[1], isDirectory: true)
    try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
    let f1080 = directory.appendingPathComponent("source-1080p-aac.mov")
    let f4k = directory.appendingPathComponent("source-4k.mov")
    let long = directory.appendingPathComponent("source-4k-120s.mov")
    try FixtureFactory.make(at: f1080, width: 1920, height: 1080, frames: 240, audio: true)
    try FixtureFactory.make(at: f4k, width: 3840, height: 2160, frames: 240)
    try FixtureFactory.make(at: long, width: 3840, height: 2160, frames: 2880)
    let cases: [(String, URL, Int?, Int)] = [
      ("1080p-copy-size", f1080, nil, 240), ("4k-copy-size", f4k, nil, 240),
      ("4k-to-1080p", f4k, 1920, 240), ("4k-120s-to-1080p", long, 1920, 2880),
    ]
    var reports: [CaseReport] = []
    let engine = MediaEngine(configuration: try EngineConfiguration())
    for (name, source, width, frames) in cases {
      var receipts: [JobReceipt] = []
      for run in 0..<6 {
        let dest = directory.appendingPathComponent("\(name)-\(run).mov")
        let request = try JobRequest(
          source: source, destination: dest, resizeWidth: width, videoBitrate: 12_000_000)
        let prepared = try await engine.prepare(request)
        let receipt = try await engine.execute(prepared)
        guard receipt.frames == frames, receipt.decoderHardware, receipt.encoderHardware else {
          throw NSError(domain: "Native acceptance failed", code: 3)
        }
        let info = try await AssetInput.open(dest)
        let reader = try SampleReader(input: info, audioPolicy: .drop)
        var count = 0
        while let sample = try reader.nextVideo() {
          guard abs(sample.pts.seconds - Double(count) / 24) < 0.000001 else {
            throw NSError(domain: "Timestamp verification failed", code: 3)
          }
          count += 1
        }
        guard count == frames else {
          throw NSError(domain: "Frame count verification failed", code: 3)
        }
        receipts.append(receipt)
        print(
          "\(name) run \(run): \(String(format:"%.3f",receipt.elapsedSeconds))s, owned peak \(receipt.ownedMemoryPeak), footprint \(receipt.processFootprintPeakBytes ?? 0)"
        )
        if run == 1 && name == "4k-to-1080p" {
          try request.normalizedData().write(
            to: directory.appendingPathComponent("completed-job.json"))
        }
        // Keep one inspectable output per case; only files generated by this tool are removed.
        if run != 1 { try FileManager.default.removeItem(at: dest) }
      }
      reports.append(
        CaseReport(
          name: name, frames: frames, warmup: receipts[0], runs: Array(receipts.dropFirst())))
    }
    let encoder = JSONEncoder()
    encoder.outputFormatting = [.prettyPrinted, .sortedKeys]
    encoder.dateEncodingStrategy = .iso8601
    let report = Report(
      os: ProcessInfo.processInfo.operatingSystemVersionString,
      processorCount: ProcessInfo.processInfo.processorCount,
      physicalMemory: ProcessInfo.processInfo.physicalMemory,
      thermalState: String(describing: ProcessInfo.processInfo.thermalState), generatedAt: Date(),
      cases: reports)
    try encoder.encode(report).write(to: directory.appendingPathComponent("benchmark.json"))
    let cli = try JobRequest(
      source: f1080, destination: directory.appendingPathComponent("cli-output.mov"),
      resizeWidth: 1280, videoBitrate: 4_000_000)
    try cli.normalizedData().write(to: directory.appendingPathComponent("cli-job.json"))
  }
}
